// Writes src/app/theme-accents.css: dark-mode versions of the light tint
// utilities (bg-amber-50, border-sky-200, text-emerald-800...). Run after
// adding a hue: node scripts/gen-theme-css.mjs
import fs from "node:fs";
import colors from "tailwindcss/colors.js";

const bridge = { 300: "#93c5fd", 400: "#60a5fa", 500: "#3b82f6", 200: "#bfdbfe" };
const HUES = ["red", "orange", "amber", "yellow", "lime", "green", "emerald", "teal", "cyan", "sky", "blue", "indigo", "violet", "purple", "fuchsia", "pink", "rose"];
const pal = Object.fromEntries(HUES.map((h) => [h, colors[h]]));
pal.bridge = bridge;
const D = 'html[data-theme="dark"]';
const PREFIXES = ["", "hover\\:", "group-hover\\:", "focus\\:", "peer-checked\\:"];
const state = (p) => (p === "hover\\:" ? ":hover" : p === "focus\\:" ? ":focus" : "");
const sel = (p, cls) => {
  if (cls.startsWith("text-")) cls = `${cls}:not(.bg-white)`;
  if (p === "group-hover\\:") return `${D} .group:hover .${p}${cls}`;
  if (p === "peer-checked\\:") return `${D} .peer:checked ~ .${p}${cls}`;
  return `${D} .${p}${cls}${state(p)}`;
};
const used = new Set();
const walk = (d) => { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = d + "/" + e.name; if (e.isDirectory()) walk(p); else if (/\.(tsx?|css)$/.test(e.name) && !p.endsWith("theme-accents.css")) for (const m of fs.readFileSync(p, "utf8").matchAll(/[\w:-]+/g)) used.add(m[0]); } };
walk("src");
let out = "/* GENERATED by scripts/gen-theme-css.mjs. Do not edit by hand. */\n";
for (const [h, c] of Object.entries(pal)) {
  const mid = c[500];
  const rules = [
    [["bg", 50], `background-color: color-mix(in srgb, ${mid} 9%, rgb(var(--surface)))`],
    [["bg", 100], `background-color: color-mix(in srgb, ${mid} 15%, rgb(var(--surface)))`],
    [["bg", 200], `background-color: color-mix(in srgb, ${mid} 30%, rgb(var(--surface)))`],
    [["border", 100], `border-color: color-mix(in srgb, ${mid} 25%, rgb(var(--surface)))`],
    [["border", 200], `border-color: color-mix(in srgb, ${mid} 35%, rgb(var(--surface)))`],
    [["border", 300], `border-color: color-mix(in srgb, ${mid} 50%, rgb(var(--surface)))`],
    [["ring", 100], `--tw-ring-color: color-mix(in srgb, ${mid} 25%, rgb(var(--surface)))`],
    [["ring", 200], `--tw-ring-color: color-mix(in srgb, ${mid} 35%, rgb(var(--surface)))`],
    [["text", 600], `color: ${c[400]}`],
    [["text", 700], `color: ${c[300]}`],
    [["text", 800], `color: ${c[300] ?? c[200]}`],
    [["text", 900], `color: ${c[200]}`],
    [["text", 950], `color: ${c[200]}`],
  ];
  for (const [[u, n], decl] of rules) {
    const list = PREFIXES.filter((p) => used.has(p.replace("\\", "") + `${u}-${h}-${n}`)).map((p) => sel(p, `${u}-${h}-${n}`));
    if (list.length) out += list.join(",\n") + ` { ${decl}; }\n`;
  }
}
fs.writeFileSync("src/app/theme-accents.css", out);
console.log("wrote", out.length, "bytes");

// Writes src/app/display.css: every `@media (prefers-reduced-motion: reduce)`
// rule in globals.css and helper.css, repeated under html[data-motion="reduce"],
// so the in-app "Reduce motion" switch (src/lib/display.ts) stops exactly what
// the operating system's setting stops. Run after editing a reduce-motion block:
//   node scripts/gen-display-css.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCES = ["src/app/globals.css", "src/app/helper.css"];
const PREFIX = 'html[data-motion="reduce"]';

/** The bodies of every reduce-motion media block in a stylesheet. */
function reduceBlocks(css) {
  const out = [];
  const re = /@media\s*\(prefers-reduced-motion:\s*reduce\)\s*\{/g;
  let m;
  while ((m = re.exec(css))) {
    let depth = 1;
    let i = re.lastIndex;
    for (; i < css.length && depth > 0; i += 1) {
      if (css[i] === "{") depth += 1;
      else if (css[i] === "}") depth -= 1;
    }
    out.push(css.slice(re.lastIndex, i - 1));
    re.lastIndex = i;
  }
  return out;
}

/** Each `selectors { declarations }` rule of a block body, comments dropped. */
function rules(body) {
  const clean = body.replace(/\/\*[\s\S]*?\*\//g, "");
  const out = [];
  let i = 0;
  while (i < clean.length) {
    const open = clean.indexOf("{", i);
    if (open < 0) break;
    const close = clean.indexOf("}", open);
    const selectors = clean
      .slice(i, open)
      .split(",")
      .map((s) => s.trim())
      .filter(Boolean);
    out.push({ selectors, decls: clean.slice(open + 1, close).trim() });
    i = close + 1;
  }
  return out;
}

let css = `/* GENERATED by scripts/gen-display-css.mjs. Do not edit by hand.
   The in-app "Reduce motion" switch (src/lib/display.ts) puts
   data-motion="reduce" on <html>; these are the stylesheets' own
   prefers-reduced-motion rules, repeated under that attribute, so the
   switch stops exactly what the operating system's setting stops. */

`;
for (const file of SOURCES) {
  const src = readFileSync(join(root, file), "utf8");
  css += `/* ---- from ${file} ---- */\n`;
  for (const body of reduceBlocks(src)) {
    for (const r of rules(body)) {
      const sel = r.selectors.map((s) => (s === "*" || s.startsWith("*::") ? `${PREFIX} ${s}` : `${PREFIX} ${s}`)).join(",\n");
      const decls = r.decls
        .split(";")
        .map((d) => d.trim())
        .filter(Boolean)
        .join(";\n  ");
      css += `${sel} {\n  ${decls};\n}\n`;
    }
  }
  css += "\n";
}
// The whole document too: html itself is not matched by "html[...] *".
css += `${PREFIX} {\n  scroll-behavior: auto !important;\n}\n`;

writeFileSync(join(root, "src/app/display.css"), css);
console.log(`wrote src/app/display.css (${css.split("\n").length} lines)`);

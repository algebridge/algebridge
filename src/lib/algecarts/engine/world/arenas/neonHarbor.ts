const ring = (n: number, r: number): Spawn[] =>
  Array.from({ length: n }, (_, i) => {
    const a = (i / n) * Math.PI * 2 + Math.PI / n;
    const x = Math.cos(a) * r;
    const z = Math.sin(a) * r;
    return { x, z, yaw: Math.atan2(-x, -z) };
  });

